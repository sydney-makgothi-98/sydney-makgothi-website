// Bundles core.js (model + maths) and ui.js (panels) into one scoped stability.js
import { readFileSync, writeFileSync } from 'node:fs';
const core = readFileSync('core.js', 'utf8').split('//#CORE-START')[1].split('//#CORE-END')[0];
const ui = readFileSync('ui.js', 'utf8').replace("'use strict';\n", '');
writeFileSync('stability.js', `/* Generated by build.mjs from core.js + ui.js. Edit those, then run: node build.mjs */\n(() => {\n'use strict';\n${core}\n${ui}\n})();\n`);
console.log('stability.js written');
